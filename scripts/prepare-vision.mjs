import { createHash } from "node:crypto";
import { cp, mkdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const source = path.join(root, "node_modules", "@mediapipe", "tasks-vision");
const destination = path.join(root, "public", "vision");
const modelUrl = "https://storage.googleapis.com/mediapipe-models/object_detector/efficientdet_lite0/int8/1/efficientdet_lite0.tflite";
await mkdir(destination, { recursive: true });
await cp(path.join(source, "vision_bundle.js"), path.join(destination, "vision_bundle.js"));
await cp(path.join(source, "wasm"), path.join(destination, "wasm"), { recursive: true });
const modelPath = path.join(destination, "efficientdet_lite0.tflite");
if (!(await stat(modelPath).catch(() => null))) {
  console.log("Downloading the person-detection model from Google...");
  const response = await fetch(modelUrl, { signal: AbortSignal.timeout(120_000) });
  if (!response.ok) throw new Error(`Model download failed (${response.status}).`);
  const model = Buffer.from(await response.arrayBuffer());
  if (model.length < 100_000 || model.length > 30 * 1024 * 1024) throw new Error("Unexpected model size.");
  await writeFile(modelPath, model);
}
const model = await readFile(modelPath);
const metadata = JSON.parse(await readFile(path.join(source, "package.json"), "utf8"));
await writeFile(path.join(destination, "NOTICE.txt"), [
  `MediaPipe Vision ${metadata.version}; Apache-2.0.`,
  "https://github.com/google-ai-edge/mediapipe",
  "EfficientDet Lite0 int8 model, version 1:", modelUrl,
  `SHA256: ${createHash("sha256").update(model).digest("hex")}`,
  "Generated by npm run vision:prepare. Video frames stay in the browser.",
].join("\n"));
console.log("Local vision runtime and model ready in public/vision.");
